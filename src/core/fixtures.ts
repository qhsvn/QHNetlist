import { applyOperations, type DesignOperation } from './patch';
import type { CircuitDocument } from './types';
import { SAMPLE_FIRMWARE } from '../sim/firmware';
import { scooterDevice } from './device';

function build(name: string, ops: DesignOperation[], sim?: Partial<CircuitDocument['sim']>): CircuitDocument {
  const base = emptyDocument(name);
  const { doc } = applyOperations(base, ops);
  return { ...doc, sim: { ...doc.sim, ...sim } };
}

